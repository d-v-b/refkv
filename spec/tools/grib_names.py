"""Writes rust/refkv-ir/src/grib/names_table.rs: the GRIB parameters' short names, names and units
(spec/zarrify/grib.md §3.2 <https://github.com/d-v-b/refkv/blob/main/spec/zarrify/grib.md#32-names>),
as ecCodes gives them for a field that names nothing but its discipline, category and number.

    uv run --no-project -p 3.13 --with eccodes==2.50.0 --with eccodeslib==2.50.0.33 python spec/tools/grib_names.py

ecCodes (Apache 2.0) names a parameter from its definitions, some of them a centre's own: so the
table holds WMO's names (centre 0, for every centre) and, where they differ or WMO has none, those
of the centres whose files the corpus holds (NCEP, 7, and ECMWF, 98). A field whose level or
statistic ecCodes' name depends on (ECMWF's `2t` is `t` at 2 m) gets the name of the parameter
alone, since the level and the statistic are the array's other names; one that ecCodes names only
at some level or for some statistic (ECMWF's sea ice cover, `ci`, at the surface) gets the name it
has at the first of a few common surface types and statistics. The table is pinned with
the ecCodes release named above; regenerating it with another is a change of the convention.
"""

from __future__ import annotations

from pathlib import Path

import eccodes

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "rust" / "refkv-ir" / "src" / "grib" / "names_table.rs"
DISCIPLINES = [0, 1, 2, 3, 4, 10, 20]
CENTRES = [0, 7, 98]
# the surfaces (code table 4.5) and statistics (4.10) tried, in order, for a parameter ecCodes does
# not name alone: the ground, a height above it, an isobaric surface, a depth below the land, the
# sea, the entire atmosphere; an accumulation, an average, a maximum, a minimum
SURFACES = [1, 103, 100, 106, 101, 10, 160]
STATISTICS = [1, 0, 2, 3]
# the parameters tried again: WMO's first categories and numbers, and the local ones
FALLBACK = [(c, n) for c in [*range(31), *range(192, 255)] for n in [*range(64), *range(192, 255)]]


def names(centre: int) -> dict[tuple[int, int, int], tuple[str, str, str]]:
    """Every (discipline, category, number) ecCodes names for `centre`: its short name, name, units."""
    h = eccodes.codes_grib_new_from_samples("GRIB2")
    eccodes.codes_set(h, "centre", centre or 255)
    eccodes.codes_set(h, "productDefinitionTemplateNumber", 0)
    eccodes.codes_set(h, "typeOfFirstFixedSurface", 255)
    eccodes.codes_set(h, "typeOfSecondFixedSurface", 255)
    out = {}
    for d in DISCIPLINES:
        eccodes.codes_set(h, "discipline", d)
        for c in range(255):
            eccodes.codes_set(h, "parameterCategory", c)
            for n in range(255):
                eccodes.codes_set(h, "parameterNumber", n)
                short = eccodes.codes_get_string(h, "shortName")
                if short in ("unknown", "~", ""):
                    continue
                out[(d, c, n)] = (short, eccodes.codes_get_string(h, "name"), eccodes.codes_get_string(h, "units"))
    eccodes.codes_release(h)
    tries = []
    combinations = [(0, s, None) for s in SURFACES] + [(8, s, p) for p in STATISTICS for s in SURFACES]
    for template, surface, process in combinations:
        t = eccodes.codes_grib_new_from_samples("GRIB2")
        eccodes.codes_set(t, "centre", centre or 255)
        eccodes.codes_set(t, "productDefinitionTemplateNumber", template)
        if process is not None:
            eccodes.codes_set(t, "typeOfStatisticalProcessing", process)
        eccodes.codes_set(t, "typeOfFirstFixedSurface", surface)
        eccodes.codes_set(t, "typeOfSecondFixedSurface", 255)
        tries.append(t)
    for d in DISCIPLINES:
        for c, n in FALLBACK:
            if (d, c, n) not in out and (found := again(tries, d, c, n)):
                out[(d, c, n)] = found
    for t in tries:
        eccodes.codes_release(t)
    return out


def again(tries: list[int], d: int, c: int, n: int) -> tuple[str, str, str] | None:
    """The name ecCodes gives the parameter at the first of SURFACES, or, with a statistic, the
    first of STATISTICS, that names it (`tries`, a message of each)."""
    for h in tries:
        for k, v in (("discipline", d), ("parameterCategory", c), ("parameterNumber", n)):
            eccodes.codes_set(h, k, v)
        short = eccodes.codes_get_string(h, "shortName")
        if short not in ("unknown", "~", ""):
            return short, eccodes.codes_get_string(h, "name"), eccodes.codes_get_string(h, "units")
    return None


def rust(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    wmo = names(0)
    rows = [(0, *k, *v) for k, v in wmo.items()]
    for centre in CENTRES[1:]:
        rows += [(centre, *k, *v) for k, v in names(centre).items() if wmo.get(k) != v]
    rows.sort()
    version = eccodes.codes_get_api_version()
    lines = [
        f"// Generated by spec/tools/grib_names.py from ecCodes {version} (Apache 2.0): do not edit.",
        "/// The parameters, by (centre, discipline, category, number).",
        "static PARAMETERS: &[Parameter] = &[",
    ]
    lines += [f"    ({c}, {d}, {k}, {n}, {rust(s)}, {rust(name)}, {rust(u)})," for c, d, k, n, s, name, u in rows]
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(rows)} parameters to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
